# ─────────────────────────────────────────────────────────────

def is_date_spot_category(category: str, name: str, allow_lodging: bool = False) -> tuple[bool, str]:
    """네이버/카카오 카테고리와 상호명이 데이트 스팟다운지 검증.
    (통과여부, 탈락사유) 반환. 애매하면 보수적으로 거부한다.

    allow_lodging: stay(숙박) 슬롯을 의도한 검색 결과에서만 True로 넘긴다.
    일반 검색에서는 숙박 카테고리 전체를 차단하지만, stay 의도 검색에서는
    SLOT_STAY_CAT_RE(진짜 숙박 카테고리)이면서 SLOT_STAY_VETO_RE(카페/식당
    등 오탐)에 안 걸리는 경우만 예외로 통과시킨다.
    """
    cat = (category or "").strip()
    cat_low = cat.lower()
    name_low = (name or "").lower()

    # 1. 상호명 자체가 명백한 비(非)스팟 패턴
    for pat in NAME_BLACKLIST_PATTERNS:
        if pat.search(name or ""):
            return False, "상호명패턴"

    # 1-a. stay 의도 검색: 진짜 숙박 카테고리면 여기서 바로 허용
    if allow_lodging and SLOT_STAY_CAT_RE.search(cat) and not SLOT_STAY_VETO_RE.search(cat_low) and not SLOT_STAY_VETO_RE.search(name_low):
        return True, ""

    # 2. 블랙리스트 (카테고리 또는 상호명)
    for bl in CATEGORY_BLACKLIST:
        if bl in cat_low or bl in name_low:
            return False, f"블랙리스트({bl.strip()})"

    # 2-a'. 토큰 완전일치 블랙리스트 (풀빌라/대림창고/현대모터스튜디오 같은
    # 브랜드 접미사 오탐을 피하려고 부분일치 대신 토큰 단위로만 본다)
    hit = _has_exact_blacklisted_token(cat) or _has_exact_blacklisted_token(name)
    if hit:
        return False, f"블랙리스트({hit})"

    if not cat:
        return False, "카테고리없음"

    # 2-a. 체인 SPA·대형 유통 브랜드 (카테고리/상호명 모두 검사)
    for br in CHAIN_BRAND_BLACKLIST:
        if br in cat_low or br in name_low:
            return False, f"체인브랜드({br})"

    # 2-b. 숙박 업종 (카테고리에만 적용). 다만 "호텔 카푸치노 루프탑 바"처럼
    # 카테고리만 숙박이고 실제로는 호텔 부대 상업공간(바/식당/갤러리 등)인
    # 경우가 있다. 상호명 마지막 토큰이 화이트리스트와 일치하면 그 업종으로
    # 보고 화이트리스트 재검사 기회를 준다(모텔/여관은 allow_lodging 자체가
    # SLOT_STAY_CAT_RE에서 이미 빠져 있어 이 구제와 무관하게 계속 거부됨).
    lodging_hit = next((bl for bl in CATEGORY_BLACKLIST_LODGING if bl in cat_low), None)
    if lodging_hit:
        name_tokens = (name or "").split()
        last_token = name_tokens[-1] if name_tokens else ""
        last_token_low = last_token.lower()
        rescued = last_token in CATEGORY_WHITELIST_EXACT or any(wl in last_token_low for wl in CATEGORY_WHITELIST)
        if not rescued:
            return False, f"숙박업종({lodging_hit})"

    # 3. 화이트리스트
    tokens = [t.strip() for t in re.split(r'[>,/·|,\s]+', cat) if t.strip()]
    for t in tokens:
        t_low = t.lower()
        if t in CATEGORY_WHITELIST_EXACT:
            return True, ""
        for wl in CATEGORY_WHITELIST:
            if wl in t_low:
                return True, ""

    # 4. 화이트리스트에도 블랙리스트에도 없는 애매한 카테고리 → 등록하지 않음
    return False, f"화이트리스트외({cat[:14]})"
